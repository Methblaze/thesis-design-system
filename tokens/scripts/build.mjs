#!/usr/bin/env node
// Design tokens build. One source in DTCG format (tokens/base.json plus one
// file per theme in tokens/themes/), many outputs, chosen in tokens/config.json:
//   css            build/tokens.css: primitives on :root, one block per theme
//   js             build/tokens.js: every theme with aliases resolved, for JS and React Native
//   tailwind       build/tailwind.js: a Tailwind colors/spacing/radius/fontFamily/boxShadow object
//   tokens-studio  build/tokens-studio.json: one multi-set file with $themes for the Tokens Studio plugin
//   figma          build/figma.json: collections, modes and text styles for the native Figma sync
// No dependencies. Run: node tokens/scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const config = read("config.json");
const base = read("base.json");
const themeFiles = readdirSync(join(root, "themes")).filter((f) => f.endsWith(".json")).sort((a, b) => (config.themeOrder || []).indexOf(a.replace(".json", "")) - (config.themeOrder || []).indexOf(b.replace(".json", "")));
const themes = Object.fromEntries(themeFiles.map((f) => [f.replace(".json", ""), JSON.parse(readFileSync(join(root, "themes", f), "utf8"))]));

// ---- helpers -------------------------------------------------------------
export const flatten = (obj, prefix = [], out = {}) => {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "$value" in v) out[[...prefix, k].join(".")] = v;
    else if (v && typeof v === "object") flatten(v, [...prefix, k], out);
  }
  return out;
};
const aliasRe = /^\{([^}]+)\}$/;
export const resolver = (tables) => {
  const resolve = (path, seen = new Set()) => {
    if (seen.has(path)) throw new Error("Alias cycle at " + [...seen, path].join(" -> "));
    seen.add(path);
    for (const t of tables) if (t[path]) {
      const v = t[path].$value;
      const m = typeof v === "string" && v.match(aliasRe);
      return m ? resolve(m[1], seen) : v;
    }
    throw new Error("Unresolved alias {" + path + "}");
  };
  return resolve;
};
const cssName = (path) => "--" + path.replace(/\./g, "-");
const px = (v) => (typeof v === "number" ? v + "px" : v);
const cssValue = (tok, path, tables) => {
  const v = tok.$value;
  const m = typeof v === "string" && v.match(aliasRe);
  if (m) return `var(${cssName(m[1])})`;
  if (tok.$type === "dimension") return px(v);
  if (tok.$type === "fontFamily") return Array.isArray(v) ? v.map((f) => (/\s/.test(f) && !f.startsWith('"') ? `"${f}"` : f)).join(", ") : v;
  if (tok.$type === "shadow") return (Array.isArray(v) ? v : [v]).map((s) => `${s.inset ? "inset " : ""}${px(s.offsetX)} ${px(s.offsetY)} ${px(s.blur)} ${px(s.spread || 0)} ${s.color}`).join(", ");
  if (tok.$type === "typography") return null; // written as separate properties below
  return String(v);
};

const baseFlat = flatten(base);
const descFile = existsSync(join(root, "descriptions.json")) ? read("descriptions.json") : {};
const groupDesc = (obj, path) => { const parts = path.split("."); let cur = obj, found; for (const k of parts.slice(0, -1)) { cur = cur?.[k]; if (cur?.$description) found = cur.$description; } return found; };
const describe = (path, tok, src) => tok.$description || descFile[path] || groupDesc(src, path);
const out = join(root, "build");
mkdirSync(out, { recursive: true });
const banner = "Generated by tokens/scripts/build.mjs from tokens/*.json. Do not edit by hand.";
const written = [];

// ---- css -------------------------------------------------------------------
if (config.outputs.includes("css")) {
  const lines = [`/* ${banner} */`, ":root {"];
  for (const [p, t] of Object.entries(baseFlat)) {
    if (t.$type === "typography") {
      const v = t.$value;
      for (const [k, val] of Object.entries(v)) lines.push(`  ${cssName(p)}-${k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}: ${typeof val === "string" && val.match(aliasRe) ? `var(${cssName(val.match(aliasRe)[1])})` : px(val)};`);
      continue;
    }
    lines.push(`  ${cssName(p)}: ${cssValue(t, p)};`);
  }
  lines.push("}");
  const names = Object.keys(themes);
  names.forEach((name, i) => {
    const sel = i === 0 ? `:root,\n[data-theme="${name}"]` : `[data-theme="${name}"]`;
    lines.push("", `${sel} {`);
    for (const [p, t] of Object.entries(flatten(themes[name]))) lines.push(`  ${cssName(p)}: ${cssValue(t, p)};`);
    lines.push("}");
  });
  writeFileSync(join(out, "tokens.css"), lines.join("\n") + "\n");
  written.push("build/tokens.css");
}

// ---- js (resolved values) ----------------------------------------------------
const resolvedTheme = (name) => {
  const flat = flatten(themes[name]);
  const resolve = resolver([flat, baseFlat]);
  const res = {};
  for (const p of Object.keys(flat)) res[p] = resolve(p);
  return res;
};
const resolvedBase = () => {
  const resolve = resolver([baseFlat]);
  const res = {};
  for (const [p, t] of Object.entries(baseFlat)) {
    if (t.$type === "typography") res[p] = Object.fromEntries(Object.entries(t.$value).map(([k, v]) => [k, typeof v === "string" && v.match(aliasRe) ? resolve(v.match(aliasRe)[1]) : v]));
    else res[p] = resolve(p);
  }
  return res;
};
const nest = (flat) => {
  const o = {};
  for (const [p, v] of Object.entries(flat)) {
    const parts = p.split(".");
    let cur = o;
    parts.slice(0, -1).forEach((k) => (cur = cur[k] ??= {}));
    cur[parts.at(-1)] = v;
  }
  return o;
};
if (config.outputs.includes("js")) {
  const data = { base: nest(resolvedBase()), themes: Object.fromEntries(Object.keys(themes).map((n) => [n, nest(resolvedTheme(n))])) };
  writeFileSync(join(out, "tokens.js"), `// ${banner}\nexport const tokens = ${JSON.stringify(data, null, 2)};\nexport default tokens;\n`);
  written.push("build/tokens.js");
}

// ---- tailwind -----------------------------------------------------------------
if (config.outputs.includes("tailwind")) {
  const rb = resolvedBase();
  const tw = config.tailwind || {};
  const pick = (group, map = (v) => v) => {
    const o = {};
    for (const [p, v] of Object.entries(rb)) if (p.startsWith(group + ".")) o[p.slice(group.length + 1)] = map(v);
    return o;
  };
  const toNested = (flatObj) => {
    const o = {};
    for (const [p, v] of Object.entries(flatObj)) {
      const parts = p.split(".").map((k) => (k === "default" ? "DEFAULT" : k));
      if (parts.length === 1) { o[parts[0]] = v; continue; }
      const head = (o[parts[0]] = typeof o[parts[0]] === "object" ? o[parts[0]] : {});
      head[parts.slice(1).join("-")] = v;
    }
    return o;
  };
  const result = {};
  if (tw.colors) {
    const cols = toNested(pick(tw.colors));
    // semantic colours as CSS variables, so themes can switch at runtime
    if (tw.semantic) for (const p of Object.keys(flatten(themes[Object.keys(themes)[0]]))) {
      const short = p.replace(/^color\./, "").replace(/\./g, "-");
      cols[short] = `var(${cssName(p)})`;
    }
    result.colors = cols;
  }
  if (tw.spacing) result.spacing = pick(tw.spacing, px);
  if (tw.radius) result.borderRadius = pick(tw.radius, px);
  if (tw.fontFamily) result.fontFamily = pick(tw.fontFamily, (v) => (Array.isArray(v) ? v.map((f) => (/\s/.test(f) ? `"${f}"` : f)) : [v]));
  if (tw.shadow) result.boxShadow = Object.fromEntries(Object.entries(baseFlat).filter(([p]) => p.startsWith(tw.shadow + ".")).map(([p, t]) => [p.slice(tw.shadow.length + 1).replace(/\./g, "-"), cssValue(t, p)]));
  writeFileSync(join(out, "tailwind.js"), `// ${banner}\nexport default ${JSON.stringify(result, null, 2)};\n`);
  written.push("build/tailwind.js");
}

// ---- tokens studio ----------------------------------------------------------
if (config.outputs.includes("tokens-studio")) {
  const ts = { base };
  for (const [n, t] of Object.entries(themes)) ts[`themes/${n}`] = t;
  ts.$themes = Object.keys(themes).map((n) => ({ id: n, name: config.themeNames?.[n] || n, selectedTokenSets: { base: "source", [`themes/${n}`]: "enabled" } }));
  ts.$metadata = { tokenSetOrder: ["base", ...Object.keys(themes).map((n) => `themes/${n}`)] };
  writeFileSync(join(out, "tokens-studio.json"), JSON.stringify(ts, null, 2) + "\n");
  written.push("build/tokens-studio.json");
}

// ---- figma ------------------------------------------------------------------
if (config.outputs.includes("figma")) {
  const fc = config.figma;
  const figPath = (p, strip) => (strip && p.startsWith(strip + ".") ? p.slice(strip.length + 1) : p).replace(/\./g, "/");
  const collections = [];
  for (const c of fc.collections) {
    const vars = [];
    if (c.source === "base") {
      for (const [p, t] of Object.entries(baseFlat)) {
        if (!c.groups.some((g) => p.startsWith(g + "."))) continue;
        const v = t.$value;
        const m = typeof v === "string" && v.match(aliasRe);
        const ftype = t.$type === "color" ? "COLOR" : t.$type === "fontFamily" ? "STRING" : "FLOAT";
        const raw = t.$type === "dimension" ? parseFloat(v) : t.$type === "fontFamily" ? (Array.isArray(v) ? v[0] : v) : v;
        vars.push({ name: figPath(p, c.strip), type: ftype, values: { [c.modes[0]]: m ? { alias: figPath(m[1], c.aliasStrip?.[m[1].split(".")[0]] ?? null) } : raw }, description: describe(p, t, base), codeSyntax: cssName(p) });
      }
    } else {
      const flatThemes = Object.fromEntries(Object.entries(themes).map(([n, t]) => [n, flatten(t)]));
      const first = Object.values(flatThemes)[0];
      for (const p of Object.keys(first)) {
        const values = {};
        for (const [n, ft] of Object.entries(flatThemes)) {
          const v = ft[p].$value;
          const m = typeof v === "string" && v.match(aliasRe);
          const modeName = config.themeNames?.[n] || n;
          values[modeName] = m ? { alias: figPath(m[1], c.aliasStrip?.[m[1].split(".")[0]] ?? null) } : v;
        }
        vars.push({ name: figPath(p, c.strip), type: "COLOR", values, description: describe(p, first[p], Object.values(themes)[0]), codeSyntax: cssName(p) });
      }
    }
    collections.push({ name: c.name, modes: c.source === "base" ? c.modes : Object.keys(themes).map((n) => config.themeNames?.[n] || n), vars, scopes: c.scopes || null, cssPrefix: c.cssPrefix || "" });
  }
  const rb = resolvedBase();
  const text = Object.entries(rb).filter(([p]) => p.startsWith(fc.typography + ".")).map(([p, v]) => {
    const t = baseFlat[p];
    const fam = Array.isArray(v.fontFamily) ? v.fontFamily[0] : v.fontFamily;
    const ls = String(v.letterSpacing ?? "0");
    return {
      name: fc.textStylePrefix + (t.$extensions?.figma?.name || p.slice(fc.typography.length + 1).replace(/\./g, "/")),
      fontFamily: fam,
      fontWeight: Number(v.fontWeight),
      fontSize: parseFloat(v.fontSize),
      lineHeight: parseFloat(v.lineHeight),
      // Figma stores letter spacing in per cent of the font size
      letterSpacingPercent: ls.endsWith("em") ? +(parseFloat(ls) * 100).toFixed(2) : ls.endsWith("px") ? +((parseFloat(ls) / parseFloat(v.fontSize)) * 100).toFixed(2) : 0,
      textCase: v.textCase === "uppercase" ? "UPPER" : "ORIGINAL",
      bind: Object.fromEntries(Object.entries(t.$value).filter(([, x]) => typeof x === "string" && aliasRe.test(x)).map(([k, x]) => [k, x.match(aliasRe)[1].split(".").join("/")])),
      description: describe(p, t, base),
    };
  });
  writeFileSync(join(out, "figma.json"), JSON.stringify({ collections, text }, null, 1) + "\n");
  written.push("build/figma.json");
}

// ---- preview ------------------------------------------------------------------
// One self-contained page that shows every token, so a change can be seen before
// it reaches a screen: a theme switch, semantic and primitive colours, the type
// scale, spacing, radius and the contrast pairs from checks.json.
if (config.outputs.includes("preview")) {
  const css = readFileSync(join(out, "tokens.css"), "utf8");
  const pv = config.preview || {};
  const themeNames = Object.keys(themes);
  const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;");
  const semantic = Object.keys(flatten(themes[themeNames[0]]));
  const prim = Object.entries(baseFlat).filter(([, t]) => t.$type === "color").map(([p]) => p);
  const typo = Object.entries(baseFlat).filter(([, t]) => t.$type === "typography");
  const space = Object.entries(baseFlat).filter(([p, t]) => t.$type === "dimension" && /(^|\.)space\./.test(p));
  const radius = Object.entries(baseFlat).filter(([p, t]) => t.$type === "dimension" && /(^|\.)radius\./.test(p));
  const v = (p) => `var(${cssName(p)})`;
  const sem = (n) => semantic.find((p) => p.endsWith(n)) || null;
  const bg = sem("bg.canvas") || sem("bg.default") || semantic[0];
  const surface = sem("bg.surface") || bg;
  const text = sem("text.primary") || semantic.find((p) => /text/.test(p));
  const muted = sem("text.secondary") || text;
  const border = sem("border.subtle") || semantic.find((p) => /border|line/.test(p)) || text;
  // contrast table, measured per theme at build time
  let contrastRows = "";
  if (existsSync(join(root, "checks.json"))) {
    const hex2 = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
    const lum = (h) => { const [r, g, b] = hex2(h).map((x) => (x <= 0.03928 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4))); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
    const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
    const rt = Object.fromEntries(themeNames.map((n) => [n, resolvedTheme(n)]));
    const baseRes = resolver([baseFlat]);
    const look = (n, p) => (p in rt[n] ? rt[n][p] : baseRes(p));
    for (const [fg, bgp, min] of read("checks.json").contrast) {
      const cells = themeNames.map((n) => { const r = ratio(look(n, fg), look(n, bgp)); return `<td class="${r >= min ? "ok" : "bad"}">${r.toFixed(2)}</td>`; }).join("");
      contrastRows += `<tr><td><code>${esc(fg)}</code></td><td><code>${esc(bgp)}</code></td><td>${min}</td>${cells}</tr>`;
    }
  }
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(pv.title || "Design tokens")}</title>${pv.fontsUrl ? `<link rel="stylesheet" href="${pv.fontsUrl}">` : ""}
<style>${css}
*{box-sizing:border-box}body{margin:0;background:${v(bg)};color:${v(text)};font-family:${pv.bodyFont || "system-ui, sans-serif"};line-height:1.5}
main{max-width:1100px;margin:0 auto;padding:32px 16px 64px}h1{font-size:32px;margin:0 0 4px}h2{font-size:20px;margin:48px 0 12px}p.lead{color:${v(muted)};margin:0 0 24px}
.switch{display:flex;gap:8px;flex-wrap:wrap;margin:16px 0}.switch button{min-height:44px;padding:0 16px;border-radius:999px;border:1px solid ${v(border)};background:${v(surface)};color:${v(text)};font:inherit;cursor:pointer}.switch button[aria-pressed=true]{outline:2px solid currentColor}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(200px,1fr));gap:12px}.sw{border:1px solid ${v(border)};border-radius:12px;overflow:hidden;background:${v(surface)}}.sw i{display:block;height:56px;border-bottom:1px solid ${v(border)}}.sw div{padding:8px 10px;font-size:12px}.sw code{font-size:12px;word-break:break-all}.sw span{display:block;color:${v(muted)}}
.type div{padding:12px 0;border-bottom:1px solid ${v(border)}}.type small{display:block;color:${v(muted)};font-family:system-ui;font-size:12px}
.bar{display:flex;align-items:center;gap:12px;margin:6px 0;font-size:13px}.bar i{display:block;height:16px;background:currentColor;opacity:.6;border-radius:4px}
table{border-collapse:collapse;width:100%;font-size:13px;background:${v(surface)};border:1px solid ${v(border)}}td,th{padding:6px 10px;border-bottom:1px solid ${v(border)};text-align:left}td.ok{color:inherit}td.bad{font-weight:700;text-decoration:underline}
.rad{display:flex;gap:16px;flex-wrap:wrap}.rad div{width:88px;height:64px;border:2px solid currentColor;display:flex;align-items:end;padding:4px;font-size:12px}
</style></head><body><main>
<h1>${esc(pv.title || "Design tokens")}</h1><p class="lead">Generated from tokens/*.json by tokens/scripts/build.mjs. ${esc(pv.lead || "")}</p>
${themeNames.length > 1 ? `<div class="switch" role="group" aria-label="Theme">${themeNames.map((n, i) => `<button type="button" aria-pressed="${i === 0}" data-t="${n}">${esc(config.themeNames?.[n] || n)}</button>`).join("")}</div>` : ""}
<h2>Semantic colours</h2><div class="grid">${semantic.map((p) => `<div class="sw"><i style="background:${v(p)}"></i><div><code>${esc(p)}</code><span data-v="${cssName(p)}"></span></div></div>`).join("")}</div>
<h2>Type</h2><div class="type">${typo.map(([p, t]) => { const val = t.$value; const st = Object.entries(val).map(([k, x]) => { const prop = { fontFamily: "font-family", fontWeight: "font-weight", fontSize: "font-size", lineHeight: "line-height", letterSpacing: "letter-spacing", textCase: "text-transform" }[k]; const m = typeof x === "string" && x.match(aliasRe); return prop ? `${prop}:${m ? v(m[1]) : px(x)}` : ""; }).join(";"); return `<div style="${st}">${esc(t.$extensions?.figma?.name || p)}<small>${esc(p)}${t.$description ? " · " + esc(t.$description) : ""}</small></div>`; }).join("")}</div>
${space.length ? `<h2>Spacing</h2>${space.map(([p, t]) => `<div class="bar"><i style="width:${v(p)}"></i><code>${esc(p)}</code> ${esc(t.$value)}</div>`).join("")}` : ""}
${radius.length ? `<h2>Radius</h2><div class="rad">${radius.map(([p, t]) => `<div style="border-radius:${v(p)}">${esc(p.split(".").pop())}</div>`).join("")}</div>` : ""}
${contrastRows ? `<h2>Contrast</h2><table><thead><tr><th>Foreground</th><th>Background</th><th>Min</th>${themeNames.map((n) => `<th>${esc(config.themeNames?.[n] || n)}</th>`).join("")}</tr></thead><tbody>${contrastRows}</tbody></table>` : ""}
<h2>Primitives</h2><div class="grid">${prim.map((p) => `<div class="sw"><i style="background:${v(p)}"></i><div><code>${esc(p)}</code><span>${esc(resolver([baseFlat])(p))}</span></div></div>`).join("")}</div>
</main><script>
const fill=()=>document.querySelectorAll("[data-v]").forEach(s=>{s.textContent=getComputedStyle(document.documentElement).getPropertyValue(s.dataset.v).trim()});
document.querySelectorAll(".switch button").forEach(b=>b.addEventListener("click",()=>{document.documentElement.dataset.theme=b.dataset.t;document.querySelectorAll(".switch button").forEach(x=>x.setAttribute("aria-pressed",x===b));fill();}));fill();
</script></body></html>`;
  writeFileSync(join(out, "preview.html"), html);
  written.push("build/preview.html");
}

console.log("tokens built:", written.join(", "));
